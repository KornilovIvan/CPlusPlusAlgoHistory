/*
 * ПОДРОБНАЯ ТЕОРИЯ КОМПИЛЯЦИИ И CMake
 * Полное руководство по процессу сборки программ на C/C++
 */

#include <stdio.h>

/* ==================== ПРОЦЕСС КОМПИЛЯЦИИ ==================== */

/*
 * ПРОЦЕСС СБОРКИ ПРОГРАММЫ состоит из трех основных этапов:
 *
 * 1. ПРЕПРОЦЕССИНГ (Preprocessing)
 *    - Обработка директив #include, #define, #ifdef, #ifndef и других
 *    - Подстановка макросов и включение заголовочных файлов
 *    - Условная компиляция различных частей кода
 *    - Результат: чистый C-код без директив препроцессора
 *
 * 2. КОМПИЛЯЦИЯ (Compilation)
 *    - Перевод препроцессированного C-кода в ассемблерный код
 *    - Оптимизация кода на различных уровнях
 *    - Проверка синтаксиса и семантики
 *    - Результат: объектные файлы (.obj на Windows, .o на Linux)
 *
 * 3. ЛИНКОВКА (Linking)
 *    - Объединение всех объектных файлов в единую программу
 *    - Разрешение внешних ссылок (вызовы функций из других файлов)
 *    - Подключение статических и динамических библиотек
 *    - Результат: исполняемый файл (.exe, .dll, .so) или библиотека
 */

/* ==================== ТИПЫ ФАЙЛОВ В СБОРКЕ ==================== */

/*
 * .c / .cpp    - исходные файлы на C/C++
 * .h / .hpp    - заголовочные файлы с объявлениями
 * .obj / .o    - объектные файлы (результат компиляции)
 * .exe         - исполняемый файл (Windows)
 * .dll         - динамическая библиотека (Windows)
 * .so          - динамическая библиотека (Linux)
 * .lib         - статическая библиотека (Windows)
 * .a           - статическая библиотека (Linux)
 */

/* ==================== ЗАГОЛОВОЧНЫЕ ФАЙЛЫ (.h) ==================== */

/*
 * ЗАГОЛОВОЧНЫЕ ФАЙЛЫ содержат:
 * - Объявления функций (прототипы)
 * - Объявления структур, объединений, перечислений
 * - Определения макросов
 * - Объявления внешних переменных
 *
 * Они НЕ содержат:
 * - Реализаций функций (код)
 * - Определений переменных (память)
 *
 * #pragma once - директива препроцессора, которая гарантирует, что заголовочный
 * файл будет включен только один раз, даже если на него есть несколько #include
 */

// Пример объявления функции в заголовочном файле
int calculate_sum(int a, int b);
void print_message(const char* message);

/* ==================== СТАТИЧЕСКИЕ БИБЛИОТЕКИ ==================== */

/*
 * СТАТИЧЕСКИЕ БИБЛИОТЕКИ (.lib на Windows, .a на Linux):
 *
 * ПРЕИМУЩЕСТВА:
 * - Код библиотеки включается непосредственно в исполняемый файл
 * - Нет зависимостей от внешних файлов при запуске
 * - Более быстрый запуск программы
 * - Проще распространение (один .exe файл)
 *
 * НЕДОСТАТКИ:
 * - Больший размер исполняемого файла
 * - Невозможность обновления библиотеки без перекомпиляции программы
 * - Дублирование кода в памяти, если несколько программ используют одну библиотеку
 *
 * ПРОЦЕСС СОЗДАНИЯ:
 * 1. Компиляция исходных файлов в объектные: clang -c library.c -o library.o
 * 2. Создание библиотеки: ar rcs liblibrary.a library.o (Linux)
 *                        lib /out:library.lib library.obj (Windows)
 */

/* ==================== ДИНАМИЧЕСКИЕ БИБЛИОТЕКИ ==================== */

/*
 * ДИНАМИЧЕСКИЕ БИБЛИОТЕКИ (.dll на Windows, .so на Linux):
 *
 * ПРЕИМУЩЕСТВА:
 * - Меньший размер исполняемого файла
 * - Разделение кода между несколькими программами
 * - Возможность обновления библиотеки без перекомпиляции программ
 * - Экономия памяти при одновременном запуске нескольких программ
 *
 * НЕДОСТАТКИ:
 * - Зависимость от наличия библиотеки в системе
 * - Более медленный запуск (загрузка библиотеки в память)
 * - Сложнее распространение (нужно поставлять .dll/.so файлы)
 * - Возможность конфликта версий библиотек
 *
 * ПРОЦЕСС СОЗДАНИЯ:
 * Windows: clang -shared -o library.dll library.c
 * Linux:   clang -shared -o liblibrary.so library.c
 *
 * МЕХАНИЗМ РАБОТЫ:
 * 1. Программа загружается в память
 * 2. Загрузчик обнаруживает ссылки на DLL
 * 3. DLL загружается в память (если еще не загружена)
 * 4. Адреса функций из DLL подставляются в программу
 * 5. Программа выполняется
 */

/* ==================== КЛЮЧЕВЫЕ ФЛАГИ КОМПИЛЯТОРА ==================== */

/*
 * ОСНОВНЫЕ ФЛАГИ КОМПИЛЯЦИИ:
 *
 * -c                    : Только компиляция, без линковки
 * -o <файл>            : Указание имени выходного файла
 * -I<путь>             : Добавление пути для поиска заголовочных файлов
 * -L<путь>             : Добавление пути для поиска библиотек
 * -l<библиотека>       : Связывание с библиотекой (без префикса lib и расширения)
 * -D<макрос>[=значение] : Определение макроса препроцессора
 * -std=<стандарт>      : Выбор стандарта языка (c89, c99, c11, c17, c23)
 * -g                   : Добавление отладочной информации
 * -O<уровень>          : Уровень оптимизации (0, 1, 2, 3, fast)
 * -Wall                : Включение всех предупреждений
 * -Wextra              : Дополнительные предупреждения
 * -Werror              : Превращение предупреждений в ошибки
 * -pedantic            : Строгое соответствие стандарту
 */

void demonstrate_compiler_flags(void)
{
	printf("\n=== ФЛАГИ КОМПИЛЯТОРА ===\n");
	printf("-O2: баланс между скоростью и размером кода\n");
	printf("-O3: агрессивная оптимизация (может увеличить размер кода)\n");
	printf("-std=c17: использование стандарта C17\n");
}

/* ==================== LTO (LINK TIME OPTIMIZATION) ==================== */

/*
 * LTO - ОПТИМИЗАЦИЯ НА ЭТАПЕ ЛИНКОВКИ:
 *
 * КАК РАБОТАЕТ:
 * - Вместо машинного кода компилятор генерирует промежуточное представление
 * - Линковщик имеет доступ ко всему коду программы одновременно
 * - Возможность оптимизации между разными модулями (файлами)
 *
 * ПРЕИМУЩЕСТВА:
 * - Inline функций между разными файлами
 * - Удаление неиспользуемого кода из всей программы
 * - Оптимизация вызовов функций между модулями
 * - Улучшенная оптимизация циклов и условий
 *
 * НЕДОСТАТКИ:
 * - Значительное увеличение времени линковки
 * - Большие требования к памяти
 * - Усложнение процесса отладки
 *
 * ВАРИАНТЫ LTO:
 * -flto      : Полная LTO (медленнее, но максимальная оптимизация)
 * -flto=thin : Тонкая LTO (быстрее, почти те же преимущества)
 */

/* ==================== INLINE ФУНКЦИИ ==================== */

/*
 * INLINE ФУНКЦИИ:
 *
 * Ключевое слово inline указывает компилятору, что рекомендуется
 * вставить тело функции непосредственно в место вызова, вместо
 * генерации обычного вызова функции.
 *
 * ПРЕИМУЩЕСТВА:
 * - Устранение накладных расходов на вызов функции
 * - Возможность дополнительной оптимизации в контексте вызова
 *
 * ОГРАНИЧЕНИЯ:
 * - Обычно работает только для функций в том же файле
 * - LTO позволяет inline между разными файлами
 * - Слишком большие inline функции могут переполнить кэш инструкций
 *
 * РЕКОМЕНДАЦИИ:
 * - Использовать для маленьких, часто вызываемых функций
 * - Избегать для больших функций
 */

static inline int square(int x)
{
	return x * x;
}

void demonstrate_inline(void)
{
	printf("\n=== INLINE ФУНКЦИИ ===\n");
	int result = square(5);	   // Компилятор может вставить 5*5 напрямую
	printf("Квадрат 5: %d\n", result);
}


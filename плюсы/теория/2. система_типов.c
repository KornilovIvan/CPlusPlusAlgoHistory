void integer_types_example(void)
{
	/*
	 * ОСНОВНЫЕ ЦЕЛОЧИСЛЕННЫЕ ТИПЫ:
	 *
	 * 1. int - базовый целочисленный тип
	 *    - Размер: обычно 32 бита (4 байта) на современных системах
	 *    - Диапазон: -2,147,483,648 до 2,147,483,647
	 *    - Исторически: -32,768 до 32,767 (16-битные системы)
	 *
	 * 2. short int (или просто short)
	 *    - Размер: 16 бит (2 байта)
	 *    - Диапазон: -32,768 до 32,767
	 *
	 * 3. long int (или просто long)
	 *    - Размер: 32 бита на x86, 64 бита на x64 системах
	 *    - Диапазон: зависит от архитектуры
	 *
	 * 4. long long int
	 *    - Размер: 64 бита (8 байт)
	 *    - Диапазон: -9,223,372,036,854,775,808 до 9,223,372,036,854,775,807
	 */

	int basic_int = 100;
	short short_var = 32000;
	long long_var = 1000000L;
	long long long_long_var = 10000000000LL;
}


void stdint_types_example(void)
{
	/*
	 * СТАНДАРТНЫЕ ТИПЫ ФИКСИРОВАННОГО РАЗМЕРА:
	 *
	 * - int8_t, int16_t, int32_t, int64_t - знаковые
	 * - uint8_t, uint16_t, uint32_t, uint64_t - беззнаковые
	 * - Гарантированный размер на всех платформах
	 * - Полезны для бинарных форматов и сетевых протоколов
	 */

	int32_t fixed32 = 1000;
	uint16_t unsigned16 = 65535;
	int64_t big_number = 123456789012345LL;

	printf("int32_t: %" PRId32 "\n", fixed32);
	printf("uint16_t: %" PRIu16 "\n", unsigned16);
	printf("int64_t: %" PRId64 "\n", big_number);
}


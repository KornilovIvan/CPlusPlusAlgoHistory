// 4. ТИПЫ РАЗМЕРОВ И УКАЗАТЕЛЕЙ
// ============================================================================
void detailed_size_t_ptrdiff_t_example(void)
{
	/*
	 * size_t - БЕЗЗНАКОВЫЙ ТИП ДЛЯ РАЗМЕРОВ И ИНДЕКСОВ
	 *
	 * ПРЕДНАЗНАЧЕНИЕ:
	 * - Хранение размеров объектов в памяти
	 * - Индексация массивов и циклы
	 * - Возвращаемое значение оператора sizeof
	 * - Параметры функций для работы с памятью (malloc, memcpy и т.д.)
	 *
	 * ОСОБЕННОСТИ:
	 * - Всегда беззнаковый (unsigned)
	 * - Размер зависит от архитектуры:
	 *   * 32-битные системы: обычно 32 бита (4 байта)
	 *   * 64-битные системы: обычно 64 бита (8 байт)
	 * - Гарантированно достаточно велик для представления размера
	 *   любого объекта в системе
	 * - Определен в заголовочных файлах: <stddef.h>, <stdio.h>, <stdlib.h>
	 *
	 * ПРЕИМУЩЕСТВА:
	 * - Переносимость между разными архитектурами
	 * - Защита от переполнения при работе с большими размерами
	 * - Единообразие в стандартной библиотеке C
	 *
	 * ФОРМАТ ВЫВОДА: %zu
	 */

	/*
	 * ptrdiff_t - ЗНАКОВЫЙ ТИП ДЛЯ РАЗНОСТИ УКАЗАТЕЛЕЙ
	 *
	 * ПРЕДНАЗНАЧЕНИЕ:
	 * - Хранение результата вычитания двух указателей
	 * - Представление расстояния между элементами в массиве
	 * - Индексация с возможностью отрицательных значений
	 *
	 * ОСОБЕННОСТИ:
	 * - Всегда знаковый (signed)
	 * - Размер зависит от архитектуры (аналогично size_t)
	 * - Может содержать отрицательные значения
	 * - Определен в <stddef.h>
	 *
	 * ЗНАЧЕНИЕ:
	 * - Разность указателей показывает количество ЭЛЕМЕНТОВ между ними,
	 *   а не количество байт
	 * - Например: &arr[5] - &arr[2] = 3 (элемента)
	 *
	 * ФОРМАТ ВЫВОДА: %td
	 */

	/*
	 * ВАЖНЫЕ ЗАМЕЧАНИЯ:
	 *
	 * 1. НИКОГДА не смешивайте int и size_t в сравнениях:
	 *    ❌ for (int i = 0; i < sizeof(array); i++) - ОПАСНО!
	 *    ✅ for (size_t i = 0; i < sizeof(array); i++) - ПРАВИЛЬНО!
	 *
	 * 2. size_t БЕЗЗНАКОВЫЙ, поэтому:
	 *    size_t a = 10;
	 *    int b = -1;
	 *    if (b < a) // Всегда true, потому что -1 преобразуется в очень большое число!
	 *
	 * 3. ptrdiff_t МОЖЕТ ПЕРЕПОЛНИТЬСЯ:
	 *    Указатели должны указывать на один массив/объект
	 *
	 * 4. Используйте правильные спецификаторы формата:
	 *    size_t: %zu
	 *    ptrdiff_t: %td
	 */
}


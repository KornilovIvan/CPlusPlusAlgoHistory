void floating_point_example(void)
{
	/*
	 * ВЕЩЕСТВЕННЫЕ ТИПЫ (IEEE-754):
	 *
	 * 1. float - одинарная точность (32 бита)
	 *    - Точность: ~7 десятичных цифр
	 *    - Диапазон: ~1.2×10^-38 до 3.4×10^38
	 *
	 * 2. double - двойная точность (64 бита)
	 *    - Точность: ~15-16 десятичных цифр
	 *    - Диапазон: ~2.2×10^-308 до 1.8×10^308
	 *
	 * 3. long double - расширенная точность
	 *    - Размер зависит от компилятора (80, 96, 128 бит)
	 */

	float f = 3.14159f;
	double d = 2.718281828459045;
	long double ld = 1.12345678901234567890L;

	printf("float: %.7f\n", f);
	printf("double: %.15f\n", d);
	printf("long double: %.20Lf\n", ld);

	// Научная нотация
	printf("Scientific: %e, %E\n", f, d);
}


void literals_example(void)
{
	/*
	 * ЛИТЕРАЛЫ В РАЗЛИЧНЫХ СИСТЕМАХ СЧИСЛЕНИЯ:
	 *
	 * Десятичная: 123
	 * Восьмеричная: 0173 (начинается с 0)
	 * Шестнадцатеричная: 0x7B (начинается с 0x или 0X)
	 * Двоичная: 0b1111011 (C23 стандарт, начинается с 0b)
	 */

	int decimal = 123;
	int octal = 0173;		   // 123 в десятичной
	int hexadecimal = 0x7B;	   // 123 в десятичной
	// int binary = 0b1111011; // C23

	printf("Decimal: %d\n", decimal);
	printf("Octal: %o (%d)\n", octal, octal);
	printf("Hexadecimal: %x (%d)\n", hexadecimal, hexadecimal);
	// printf("Binary: %d\n", binary);
}


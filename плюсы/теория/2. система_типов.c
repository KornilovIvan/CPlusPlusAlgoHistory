void signed_unsigned_example(void)
{
	/*
	 * БЕЗЗНАКОВЫЕ И ЗНАКОВЫЕ ТИПЫ:
	 *
	 * - unsigned: только неотрицательные числа (0 и выше)
	 * - signed: отрицательные и положительные числа
	 * - По умолчанию int является signed
	 * - Переполнение unsigned определено (modulo 2^n)
	 * - Переполнение signed - неопределенное поведение
	 */

	unsigned int positive = 4000000000U;
	int regular = -100;
	unsigned char small = 255;

	printf("unsigned int: %u\n", positive);
	printf("signed int: %d\n", regular);
	printf("unsigned char: %u\n", small);
}


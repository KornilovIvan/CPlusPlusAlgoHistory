void input_output_example(void)
{
	/*
	 * СПЕЦИФИКАТОРЫ ФОРМАТА ДЛЯ printf/scanf:
	 *
	 * short:      %hd или %hi
	 * int:        %d или %i
	 * long:       %ld
	 * long long:  %lld
	 *
	 * unsigned:   %u, %lu, %llu
	 * hexadecimal:%x или %X
	 * octal:      %o
	 *
	 * size_t:     %zu
	 * ptrdiff_t:  %td
	 */

	int regular_int;
	unsigned short ushort_var;
	long long big_int;

	printf("Введите int, unsigned short и long long: ");
	scanf("%d %hu %lld", &regular_int, &ushort_var, &big_int);

	printf("Вы ввели: %d, %hu, %lld\n", regular_int, ushort_var, big_int);
	printf("Hex: %x, Octal: %o\n", regular_int, regular_int);
}


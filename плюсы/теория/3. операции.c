/*
 * Файл: operations_complete.c
 * Описание: Полное руководство по операциям и конструкциям в языке C
 */

#include <stdio.h>
#include <stdlib.h>

int main(void)
{
	/* ==================== */
	/* АРИФМЕТИЧЕСКИЕ ОПЕРАЦИИ */
	/* ==================== */

	/*
	 * Базовые арифметические операции:
	 * + - сложение
	 * - - вычитание
	 * * - умножение
	 * / - деление
	 * % - остаток от деления (только для целых чисел)
	 */

	int a = 10, b = 3;
	printf("Арифметические операции:\n");
	printf("%d + %d = %d\n", a, b, a + b);
	printf("%d - %d = %d\n", a, b, a - b);
	printf("%d * %d = %d\n", a, b, a * b);
	printf("%d / %d = %d\n", a, b, a / b);	   // Результат: 3 (целочисленное деление)
	printf("%d %% %d = %d\n", a, b, a % b);	   // Результат: 1

	/* ==================== */
	/* ОСОБЕННОСТИ ТИПОВ */
	/* ==================== */

	/*
	 * 1. При смешивании типов происходит автоматическое преобразование
	 *    (int + float → float + float)
	 * 2. Преобразование идет к типу с более высоким рангом
	 * 3. Ранг типов: char < short < int < long < float < double
	 */

	int x = 5;
	float y = 2.5f;
	float result = x + y;	 // int автоматически преобразуется в float
	printf("\nСмешивание типов: %d + %.1f = %.1f\n", x, y, result);

	/*
	 * 4. Целочисленное деление округляет в сторону нуля
	 * 5. Деление на ноль → неопределенное поведение
	 * 6. Переполнение signed типов → неопределенное поведение
	 */

	/* ==================== */
	/* ОПЕРАТОРЫ ПРИСВАИВАНИЯ И СРАВНЕНИЯ */
	/* ==================== */

	/*
	 * Операторы сравнения:
	 * == - равно
	 * != - не равно
	 * <  - меньше
	 * <= - меньше или равно
	 * >  - больше
	 * >= - больше или равно
	 */

	int i = 5, j = 3;
	printf("\nОператоры сравнения:\n");
	printf("%d == %d: %d\n", i, j, i == j);	   // 0 (false)
	printf("%d != %d: %d\n", i, j, i != j);	   // 1 (true)
	printf("%d <  %d: %d\n", i, j, i < j);	   // 0
	printf("%d >  %d: %d\n", i, j, i > j);	   // 1

	/*
	 * Составные операторы присваивания:
	 * +=, -=, *=, /=, %=, &=, |=, ^=
	 */

	int n = 10;
	n += 5;	   // эквивалентно n = n + 5
	printf("\nСоставное присваивание: n += 5 → %d\n", n);

	/* ==================== */
	/* УСЛОВНЫЕ КОНСТРУКЦИИ */
	/* ==================== */

	/*
	 * ВАЖНО: не путать = (присваивание) и == (сравнение)
	 */

	/* ==================== */
	/* БЛОКИ И ОБЛАСТИ ВИДИМОСТИ */
	/* ==================== */

	{
		// Внутренний блок - создает новую область видимости
		int local_var = 42;
		printf("Локальная переменная в блоке: %d\n", local_var);
	}
	// local_var здесь уже не доступна

	/* ==================== */
	/* ЦИКЛЫ */
	/* ==================== */

	// Цикл while - проверка условия ДО выполнения
	int counter = 0;
	while (counter < 3)
	{
		printf("while: counter = %d\n", counter);
		counter++;
	}

	// Цикл do-while - проверка условия ПОСЛЕ выполнения
	counter = 0;
	do
	{
		printf("do-while: counter = %d\n", counter);
		counter++;
	} while (counter < 3);

	// Цикл for - компактная форма
	for (int i = 0; i < 3; i++)
	{
		printf("for: i = %d\n", i);
	}

	/* ==================== */
	/* ОПЕРАТОРЫ ПЕРЕХОДА */
	/* ==================== */

	// break - немедленный выход из цикла
	// continue - переход к следующей итерации

	/* ==================== */
	/* РАБОТА С ФАЙЛАМИ */
	/* ==================== */

	/*
	 * Режимы открытия файлов:
	 * "r"  - чтение (файл должен существовать)
	 * "w"  - запись (создает или перезаписывает файл)
	 * "a"  - добавление в конец
	 * "r+" - чтение и запись
	 * "w+" - чтение и запись (создает или перезаписывает)
	 * "a+" - чтение и добавление
	 */

	FILE *fin = NULL;
	FILE *fout = NULL;

	// Всегда проверяем результат открытия файла!
	fin = fopen("input.txt", "r");
	if (fin == NULL)
	{
		printf("Ошибка: не удалось открыть input.txt для чтения\n");
		// В реальной программе здесь должна быть обработка ошибки
	}

	fout = fopen("output.txt", "w");
	if (fout == NULL)
	{
		printf("Ошибка: не удалось открыть output.txt для записи\n");
		// Обработка ошибки
	}

	// Пример работы с файлами (если они успешно открыты)
	if (fin != NULL && fout != NULL)
	{
		int file_x, file_y;

		// Чтение из файла
		if (fscanf(fin, "%d%d", &file_x, &file_y) == 2)
		{
			// Запись в файл
			fprintf(fout, "Сумма: %d + %d = %d\n", file_x, file_y, file_x + file_y);
			printf("Данные успешно обработаны и записаны в output.txt\n");
		}
		else
		{
			printf("Ошибка чтения данных из файла\n");
		}
	}

	// Всегда закрывайте файлы!
	if (fin != NULL)
	{
		fclose(fin);
		fin = NULL;	   // Хорошая практика - обнулять указатель после закрытия
	}

	if (fout != NULL)
	{
		fclose(fout);
		fout = NULL;
	}

	/* ==================== */
	/* АРГУМЕНТЫ КОМАНДНОЙ СТРОКИ */
	/* ==================== */

	/*
	 * int main(int argc, char *argv[])
	 * argc - количество аргументов (включая имя программы)
	 * argv - массив строк-аргументов
	 *
	 * Пример: myprogram input.txt output.txt
	 * argc = 3
	 * argv[0] = "myprogram"
	 * argv[1] = "input.txt"
	 * argv[2] = "output.txt"
	 */
	return 0;
}

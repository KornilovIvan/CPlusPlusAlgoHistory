// 🔵 СТЕК (STACK) - автоматическое управление памятью
void stack_example(void)
{
	int local_var = 42;			  // ✅ Переменная на стеке
	char name[64] = "Example";	  // ✅ Массив на стеке
	double values[10];			  // ✅ Массив на стеке

	// Память автоматически очистится при выходе из функции
}

// 🟡 КУЧА (HEAP) - ручное управление памятью
void heap_example(void)
{
	// ✅ Выделение памяти на куче
	int *dynamic_array = malloc(10 * sizeof(int));

	// ❗ ВАЖНО: Всегда проверяйте результат malloc
	if (dynamic_array == NULL)
	{
		printf("❌ Ошибка выделения памяти!\n\n");
		return;
	}

	// Использование выделенной памяти
	for (int i = 0; i < 10; i++)
	{
		dynamic_array[i] = i * i;
	}

	// ❗ ОБЯЗАТЕЛЬНО освобождайте память!
	free(dynamic_array);
}


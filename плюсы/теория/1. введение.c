/*
 * 1. ПРЕПРОЦЕССОР ЗАМЕНЯЕТ #include СОДЕРЖИМЫМ ФАЙЛА:
 *    #include <stdio.h>  →  содержимое файла stdio.h
 *    #include "myfile.h" →  содержимое файла myfile.h
 *
 * 2. РАЗНИЦА МЕЖДУ < > и " ":
 *    #include <file.h>   - поиск в системных директориях
 *    #include "file.h"   - поиск в текущей директории, затем в системных
 *
 * 3. ПРОЦЕСС КОМПИЛЯЦИИ:
 *    Исходный код → Препроцессор → Компилятор → Исполняемый файл
 *           (.c)  →     (.i)     →    (.o)    →       (.exe)
 *
 * 4. ЗАЩИТА ОТ МНОГОКРАТНОГО ВКЛЮЧЕНИЯ:
 *    #ifndef MYHEADER_H
 *    #define MYHEADER_H
 *    // содержимое header файла
 *    #endif
 *
 * 5. ВЛОЖЕННЫЕ INCLUDE:
 *    Если file1.h включает file2.h, а main.c включает file1.h
 *    то file2.h также будет включен в main.c
 */


void file_paths_example(void)
{
	// ❌ ПРОБЛЕМА: обратный слеш - символ экранирования в C
	// char *path = "c:\temp\file.txt"; // НЕПРАВИЛЬНО!

	// ✅ ПРАВИЛЬНЫЕ СПОСОБЫ:

	// Способ 1: Экранирование обратного слеша
	char *path1 = "c:\\temp\\file.txt";
	printf("Путь с экранированием: %s\n", path1);

	// Способ 2: Использование прямых слешей (работает в Windows)
	char *path2 = "c:/temp/file.txt";
	printf("Путь с прямыми слешами: %s\n", path2);

	// Способ 3: RAW string (C11 стандарт)
	char *path3 = "c:\\temp\\file.txt";
	printf("RAW строка: %s\n", path3);

	printf("\n");
}
